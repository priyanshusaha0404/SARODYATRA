const I18N = {
  LANGS: [['en', 'EN'], ['bn', 'বাংলা'], ['hi', 'हिंदी']],
  INDEX: { en: 0, bn: 1, hi: 2 },
  NAMES: { en: 'English', bn: 'Bengali (বাংলা)', hi: 'Hindi (हिंदी)' },
  LOCALE: { en: 'en-IN', bn: 'bn-IN-u-nu-latn', hi: 'hi-IN-u-nu-latn' },
  lang: 'en',

  init() {
    let saved = 'en';
    try { saved = localStorage.getItem('pujox:lang') || 'en'; } catch {}
    this.lang = this.INDEX[saved] != null ? saved : 'en';
    document.documentElement.lang = this.lang;
  },
  set(lang) {
    if (this.INDEX[lang] == null || lang === this.lang) return;
    this.lang = lang;
    try { localStorage.setItem('pujox:lang', lang); } catch {}
    document.documentElement.lang = lang;
    this.apply();
    U.emit('lang', lang);
  },
  /** fill data-i18n (text), data-i18n-ph (placeholder), data-i18n-title (title + aria-label) */
  apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
    root.querySelectorAll('[data-i18n-title]').forEach(el => { const v = t(el.dataset.i18nTitle); el.title = v; el.setAttribute('aria-label', v); });
  },
};

/** translate a key with {placeholders} */
function t(key, vars) {
  const row = STR[key];
  let s = row ? (row[I18N.INDEX[I18N.lang]] || row[0]) : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}
/** localized display name for a metro station / pandal feature's properties */
function locName(p) { return (I18N.lang === 'bn' && p.name_bn) || (I18N.lang === 'hi' && p.name_hi) || p.name; }
/** any localized attribute: locField(p, 'locality') → locality_bn / locality_hi / locality */
function locField(p, k) { return (I18N.lang !== 'en' && p[k + '_' + I18N.lang]) || p[k] || ''; }
